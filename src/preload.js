const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('hub', {
  getState: () => ipcRenderer.invoke('state:get'),
  setState: (s) => ipcRenderer.send('state:set', s),
  onPush: (fn) => ipcRenderer.on('state:push', (_e, s) => fn(s)),
  // layout: the main process owns which windows are showing; windows just ask
  getCtx: () => ipcRenderer.invoke('ui:ctx'),
  onCtx: (fn) => ipcRenderer.on('ui:ctx', (_e, c) => fn(c)),
  onShow: (fn) => ipcRenderer.on('ui:show', () => fn()),
  onDataChanged: (fn) => ipcRenderer.on('data:changed', () => fn()),
  setMode: (m) => ipcRenderer.send('ui:setMode', m),
  goto: (k) => ipcRenderer.send('ui:goto', k),
  warm: (r) => ipcRenderer.send('ui:warm', r),
  hideWindow: () => ipcRenderer.send('ui:hide'),
  openLink: (url) => ipcRenderer.send('open:link', url),
  openClaude: (o) => ipcRenderer.send('open:claude', o || {}),
  openTerminal: () => ipcRenderer.send('open:terminal'),
  openFolder: (o) => ipcRenderer.send('open:folder', o),
  locations: () => ipcRenderer.invoke('locations:get'),
  setAutoLaunch: (on) => ipcRenderer.send('app:autoLaunch', on),
  quit: () => ipcRenderer.send('app:quit'),
  notify: (p) => ipcRenderer.send('notify', p),
  nudgeStatus: () => ipcRenderer.invoke('nudge:status'),
  bannerAction: (kind, action) => ipcRenderer.send('banner:action', kind, action),
  goals: () => ipcRenderer.invoke('goals:get'),
  toggleGoal: (line, raw, done) => ipcRenderer.invoke('goals:toggle', line, raw, done),
  triage: () => ipcRenderer.invoke('triage:get'),
  projects: () => ipcRenderer.invoke('projects:get'),
  digest: () => ipcRenderer.invoke('digest:get'),
  plan: () => ipcRenderer.invoke('plan:get'),
  runDigest: () => ipcRenderer.invoke('digest:run'),
  refreshNews: () => ipcRenderer.invoke('news:refresh'),
});
